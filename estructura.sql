CREATE TABLE clientes (
    cliente_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    ciudad VARCHAR(80) NOT NULL,
    fecha_alta DATE NOT NULL
);

CREATE TABLE productos (
    producto_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_producto VARCHAR(120) NOT NULL,
    categoria VARCHAR(60) NOT NULL,
    precio_lista NUMERIC(10,2) NOT NULL CHECK (precio_lista >= 0)
);

CREATE TABLE pedidos (
    pedido_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL,
    producto_id INTEGER NOT NULL,
    fecha_pedido DATE,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2),
    estado VARCHAR(20) NOT NULL CHECK (
        estado IN ('entregado', 'cancelado')
    ),

-- Se definen claves foraneas entre tablas.
    CONSTRAINT fk_pedidos_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES clientes(cliente_id),

    CONSTRAINT fk_pedidos_producto
        FOREIGN KEY (producto_id)
        REFERENCES productos(producto_id)
);

