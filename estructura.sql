-- LIMPIEZA
-- Si falta el precio cobrado, usamos el precio de lista vigente del producto.
UPDATE pedidos AS pe
SET precio_unitario = COALESCE(pe.precio_unitario, pr.precio_lista)
FROM productos AS pr
WHERE pe.producto_id = pr.producto_id
  AND pe.precio_unitario IS NULL;

-- Una fecha desconocida no se reemplaza por una fecha inventada. Se conserva el registro,
-- pero queda fuera de los analisis temporales hasta revisar la fuente original.

-- Comprobamos si quedan valores nulos en columnas importantes.
SELECT
    COUNT(*) FILTER (WHERE precio_unitario IS NULL) AS precios_nulos,
    COUNT(*) FILTER (WHERE fecha_pedido IS NULL) AS fechas_nulas
FROM pedidos;

-- CONTROL DE ESTRUCTURA
-- Verificamos que las fechas y los precios tengan los tipos solicitados.
SELECT
    table_name,
    column_name,
    data_type,
    numeric_precision,
    numeric_scale
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name IN ('productos', 'pedidos')
  AND column_name IN (
      'fecha_pedido',
      'precio_lista',
      'precio_unitario'
  )
ORDER BY table_name, column_name;